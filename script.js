function adaptQuestions(raw) {
    return raw.map(q => ({
        topic: `${q.level} класс: ${q.topic}`,
        type: "input",
        question: q.question,
        correctAnswer: [q.answer],       // массив — чтобы handleInputSubmit не падал
        explanation: q.answer           // показываем ответ как пояснение
    }));
}

